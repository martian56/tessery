type Files = Record<string, string>

const pascal = (s: string) => s.replace(/(^|[-_\s/[\]]+)(\w)/g, (_, __, c: string) => c.toUpperCase()).replace(/[^A-Za-z0-9]/g, '')
const camel = (s: string) => s.replace(/-(\w)/g, (_, c: string) => c.toUpperCase())
const routeDir = (route: string) => (route === '/' ? '' : route.replace(/^\//, '') + '/')
const routeParams = (route: string) => [...route.matchAll(/\[(\w+)\]/g)].map((m) => m[1])

function opParams(doc: ProjectDoc, nodeId: string, opName: string): { params: number; body: boolean } {
  const op = doc.apis[nodeId]?.operations.find((o) => o.name === opName)
  if (!op) return { params: 0, body: false }
  const [m, path] = op.kind.split(' ')
  if (!path) return { params: 0, body: false }
  return { params: [...path.matchAll(/\{(\w+)\}/g)].length, body: ['POST', 'PUT', 'PATCH'].includes(m) }
}

function actionExpr(doc: ProjectDoc, action: unknown, params: string[]): string {
  if (typeof action !== 'string' || !action.includes(':')) return ''
  const [nid, opName] = action.split(':')
  const svc = doc.nodes.find((n) => n.id === nid)?.name
  const op = doc.apis[nid]?.operations.find((o) => o.name === opName)
  const route = op ? httpRoute(op) : null
  if (!svc || !route) return ''
  const prefix = restPrefix(doc.apis[nid])
  const path = (prefix && !route.path.startsWith(`${prefix}/`) ? prefix + route.path : route.path).replace(/\{(\w+)\}/g, (m, name: string) => (params.includes(name) ? `\${${name}}` : m))
  return `{ service: ${JSON.stringify(svc)}, method: ${JSON.stringify(route.method)}, path: \`${path}\` }`
}

export function pageSource(doc: ProjectDoc, p: Page): string {
  const params = routeParams(p.route)
  const auth = !!builtInAuth(doc)
  const blocks = blocksOf(p.root)
  const loads: [string, string][] = []
  const live = p.render === 'ssr'
  for (const [i, b] of blocks.entries()) {
    const src = b.props.source
    if (typeof src !== 'string' || !src.includes(':')) continue
    const [nid, op] = src.split(':')
    const svc = doc.nodes.find((n) => n.id === nid)?.name
    const spec = doc.apis[nid]
    const operation = spec?.operations.find((o) => o.name === op)
    if (!svc || !operation || (spec.style !== 'graphql' && spec.style !== 'grpc' && !httpRoute(operation))) continue
    if (!readsOnly(spec.style, operation)) continue
    const { params: n, body } = opParams(doc, nid, op)
    const args = [...Array.from({ length: n }, (_, k) => params[k] ?? "''"), ...(body ? ['{}'] : [])]
    const opts = [auth ? 'token' : '', live && spec.style === 'rest' ? 'query: search' : ''].filter(Boolean)
    if (opts.length) args.push(`{ ${opts.join(', ')} }`)
    loads.push([b.id, `  const data${i} = await api.${camel(svc)}.${op}(${args.join(', ')}).catch(() => null)`])
  }
  const data = loads.map(([id], k) => `${JSON.stringify(id)}: ${loads[k][1].match(/const (data\d+)/)![1]}`)
  const actions = blocks.map((b) => [b.id, actionExpr(doc, b.props.action, params)] as const).filter(([, e]) => e).map(([id, e]) => `${JSON.stringify(id)}: ${e}`)
  const current = params.length ? `\`${p.route.replace(/\[(\w+)\]/g, (_m, x: string) => `\${${x}}`)}\`` : JSON.stringify(p.route)
  const mode = p.render === 'isr' ? 'export const revalidate = 60\n' : p.render === 'ssg' ? "export const dynamic = 'force-static'\n" : "export const dynamic = 'force-dynamic'\n"
  const takes = [params.length ? 'params' : '', live ? 'searchParams' : ''].filter(Boolean)
  const types = [params.length ? `params: Promise<{ ${params.map((x) => `${x}: string`).join('; ')} }>` : '', live ? 'searchParams: Promise<Record<string, string | string[] | undefined>>' : ''].filter(Boolean)
  const props = takes.length ? `{ ${takes.join(', ')} }: { ${types.join('; ')} }` : ''
  return `// ${p.name} (${p.route}), ${p.render.toUpperCase()}, generated by Tessery from the page design
${mode}import { Tree, type El } from '@/components/tree'
import { BLOCKS, BLOCK_DEFAULTS } from '@/components'
import { Icon } from '@/components/icon'
${loads.length ? "import { api } from '@/lib/api'\n" : ''}${p.access !== 'public' || (auth && loads.length) ? `import { ${[p.access !== 'public' ? 'requireSession' : '', auth && loads.length ? 'sessionToken' : ''].filter(Boolean).join(', ')} } from '@/lib/auth'\n` : ''}
export const metadata = { title: ${JSON.stringify(p.title || p.name)} }

const root: El = ${JSON.stringify(p.root)}
const theme = ${JSON.stringify(themeOf(doc, p.appNodeId))}

export default async function ${pascal(p.name) || 'Index'}Page(${props}) {
${params.length ? `  const { ${params.join(', ')} } = await params\n` : ''}${live ? '  const search = await searchParams\n' : ''}${p.access !== 'public' ? `  await requireSession(${p.access === 'admin' ? "'admin'" : ''})\n` : ''}${auth && loads.length ? '  const token = await sessionToken()\n' : ''}${loads.map(([, l]) => l).join('\n')}${loads.length ? '\n' : ''}  return <Tree root={root} theme={theme} blocks={BLOCKS} defaults={BLOCK_DEFAULTS} icon={Icon} path={${current}}${live ? ' query={search}' : ''}${data.length ? ` data={{ ${data.join(', ')} }}` : ''}${actions.length ? ` actions={{ ${actions.join(', ')} }}` : ''} />
}
`
}

