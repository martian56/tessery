export function webAppFiles(doc: ProjectDoc, app: SystemNode): Files {
  const dir = `apps/${app.name}`
  const pages = doc.pages.filter((p) => p.appNodeId === app.id)
  const framework = String(app.config.framework ?? 'Next.js')
  const f: Files = {}
  f[`${dir}/lib/api.ts`] = apiClient(doc)
  pages.forEach((p) => { f[`${dir}/app/${routeDir(p.route)}page.tsx`] = pageSource(doc, p) })
  if (!framework.startsWith('Next')) {
    f[`${dir}/README.md`] = `# ${app.name}\n\n${framework} projects are not scaffolded yet. The pages under \`app/\` are written for Next.js (App Router) and the API client in \`lib/api.ts\` works with any framework.\n`
    return f
  }
  f[`${dir}/package.json`] = JSON.stringify({
    name: app.name, private: true, version: '0.1.0',
    scripts: { dev: 'next dev', build: 'next build', start: 'next start' },
    dependencies: { next: '^16.0.0', react: '^19.0.0', 'react-dom': '^19.0.0', 'lucide-react': '^0.511.0' },
    devDependencies: { typescript: '^5.9.0', '@types/node': '^24.0.0', '@types/react': '^19.0.0', '@types/react-dom': '^19.0.0' },
  }, null, 2) + '\n'
  f[`${dir}/tsconfig.json`] = JSON.stringify({
    compilerOptions: { target: 'ES2022', lib: ['dom', 'dom.iterable', 'esnext'], allowJs: false, skipLibCheck: true, strict: true, noEmit: true, esModuleInterop: true, module: 'esnext', moduleResolution: 'bundler', resolveJsonModule: true, isolatedModules: true, jsx: 'preserve', incremental: true, plugins: [{ name: 'next' }], paths: { '@/*': ['./*'] } },
    include: ['next-env.d.ts', '**/*.ts', '**/*.tsx', '.next/types/**/*.ts'],
    exclude: ['node_modules'],
  }, null, 2) + '\n'
  f[`${dir}/next.config.mjs`] = "/** @type {import('next').NextConfig} */\nexport default { output: 'standalone' }\n"
  f[`${dir}/next-env.d.ts`] = '/// <reference types="next" />\n/// <reference types="next/image-types/global" />\n'
  f[`${dir}/app/layout.tsx`] = `import './globals.css'
import type { ReactNode } from 'react'

export const metadata = { title: ${JSON.stringify(doc.name)} }

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <body><div className="tsp">{children}</div></body>
    </html>
  )
}
`
  f[`${dir}/app/globals.css`] = BASE_CSS + '\n' + BLOCK_STYLES
  f[`${dir}/app/api/[service]/[...path]/route.ts`] = apiProxy(doc, app)
  const auth = builtInAuth(doc)
  if (auth) {
    f[`${dir}/lib/session.ts`] = SESSION_RUNTIME
    f[`${dir}/lib/auth.ts`] = NEXT_AUTH
    if (!pages.some((p) => p.route === '/login')) f[`${dir}/app/login/page.tsx`] = NEXT_LOGIN.replaceAll('__AUTH__', auth.name)
    f[`${dir}/app/logout/route.ts`] = `import { NextResponse } from 'next/server'\n\nexport function GET(req: Request) {\n  const res = NextResponse.redirect(new URL('/', req.url))\n  res.cookies.delete('session')\n  return res\n}\n`
  } else if (!pages.some((p) => p.route === '/login') && pages.some((p) => p.access !== 'public')) {
    f[`${dir}/app/login/page.tsx`] = "export default function LoginPage() {\n  return <form className=\"form\"><h1>Sign in</h1><label>Email<input name=\"email\" type=\"email\" /></label><button className=\"btn\">Continue</button></form>\n}\n"
  }
  if (!pages.some((p) => p.route === '/')) f[`${dir}/app/page.tsx`] = `export default function Home() {\n  return <h1>${app.name}</h1>\n}\n`
  f[`${dir}/components/index.tsx`] = COMPONENTS
  f[`${dir}/components/blocks.tsx`] = BLOCKS_SOURCE
  f[`${dir}/components/tree.tsx`] = TREE_SOURCE
  f[`${dir}/components/icon.tsx`] = ICON
  f[`${dir}/components/form.tsx`] = FORM
  if (!auth) f[`${dir}/lib/auth.ts`] = AUTH
  f[`${dir}/Dockerfile`] = `FROM node:24-alpine AS build
WORKDIR /app
COPY package.json ./
RUN npm install --no-audit --no-fund
COPY . .
RUN npm run build

# The standalone build only ships what the app imports, so tracing lives in its own folder and is
# loaded only when OTEL_EXPORTER_OTLP_ENDPOINT is set.
FROM node:24-alpine AS otel
WORKDIR /otel
RUN npm install --no-audit --no-fund --omit=dev @opentelemetry/api@^1.10.0 @opentelemetry/auto-instrumentations-node@^0.82.0 \\
 && echo "import '@opentelemetry/auto-instrumentations-node/register'" > register.mjs

FROM node:24-alpine
WORKDIR /app
ENV NODE_ENV=production PORT=3000 HOSTNAME=0.0.0.0
COPY --from=otel /otel /otel
COPY --from=build /app/.next/standalone ./
COPY --from=build /app/.next/static ./.next/static
COPY --from=build /app/public ./public
USER node
EXPOSE 3000
CMD ["sh", "-c", "exec node \${OTEL_EXPORTER_OTLP_ENDPOINT:+--import /otel/register.mjs} server.js"]
`
  f[`${dir}/.dockerignore`] = 'node_modules\n.next\n'
  f[`${dir}/public/robots.txt`] = 'User-agent: *\nAllow: /\n'
  f[`${dir}/README.md`] = `# ${app.name}\n\nNext.js app generated by Tessery with ${pages.length} page${pages.length === 1 ? '' : 's'}.\n\n    npm install && npm run dev\n\nEach service it calls is reached at \`<SERVICE>_URL\` (for example \`NOTES_API_URL\`); the browser goes through \`/api/<service>\`.\n`
  return f
}
