const ICON = `// Draws page icons by their Lucide name (lucide.dev/icons), such as "git-branch" or "shopping-cart".
import { icons, type LucideIcon } from 'lucide-react'

const squash = (name: string) => name.replace(/[^A-Za-z0-9]/g, '').toLowerCase()
const BY_NAME = new Map(Object.keys(icons).map((key) => [squash(key), key]))

export function Icon({ name, ...rest }: { name: string; className: string; 'aria-hidden'?: boolean; 'aria-label'?: string; 'data-node'?: string }) {
  const key = BY_NAME.get(squash(name))
  const Found = key ? (icons as Record<string, LucideIcon>)[key] : undefined
  return Found ? <Found {...rest} /> : <span className={rest.className} aria-hidden />
}
`

const FORM = `'use client'
// Submits to the operation the form is bound to, through this app's /api/<service> proxy.
import { useRouter } from 'next/navigation'
import { useState, type FormEvent } from 'react'
import { FormView } from './blocks'

type Action = { service: string; method: string; path: string }

export function Form({ title, fields, submit, action }: { title?: string; fields?: string; submit?: string; action?: Action }) {
  const router = useRouter()
  const [error, setError] = useState('')
  const [busy, setBusy] = useState(false)

  async function onSubmit(e: FormEvent<HTMLFormElement>) {
    e.preventDefault()
    if (!action) return setError('This form is not connected to an operation yet.')
    const form = e.currentTarget
    const body = Object.fromEntries([...new FormData(form).entries()].filter(([, v]) => v !== ''))
    setBusy(true)
    try {
      const r = await fetch(\`/api/\${action.service}\${action.path}\`, { method: action.method, headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })
      if (!r.ok) {
        const b = await r.json().catch(() => ({}))
        return setError(b.detail ?? b.error ?? \`Request failed with \${r.status}\`)
      }
      form.reset()
      setError('')
      router.refresh()
    } catch {
      setError('Could not reach the server.')
    } finally {
      setBusy(false)
    }
  }

  return <FormView title={title} fields={fields} submit={submit} busy={busy} error={error} onSubmit={onSubmit} />
}
`

const AUTH = `import { cookies } from 'next/headers'
import { redirect } from 'next/navigation'

/** Redirects to /login unless a session cookie is present. Replace with your identity provider's check. */
export async function requireSession(role?: 'admin') {
  const session = (await cookies()).get('session')?.value
  if (!session) redirect('/login')
  return { role }
}
`

