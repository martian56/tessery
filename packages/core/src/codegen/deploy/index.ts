import type { SystemNode, DeployTarget, Environment, ProjectDoc } from '../../domain/types'
import { TECH_BY_ID } from '../../catalog/technologies'
import { devCompose, envCompose, envExample, slug } from './compose'
import { manifests, namespaceOf, publicHost } from './kubernetes'
import { connection, hostPort, secrets, workloads, type SecretSpec } from './runtime'

export * from './runtime'
export { devCompose, envCompose, manifests, namespaceOf, slug }

export interface DeployPlan {
  version: 1
  project: string
  env: string
  target: DeployTarget
  namespace?: string
  builds: { name: string; context: string }[]
  secrets: SecretSpec[]
  endpoints: { name: string; url: string }[]
  rollout: { kind: 'deployment' | 'statefulset'; name: string }[]
  checks: { name: string; port: number; path: string }[]
  autoRollback: boolean
}

export const targetOf = (env: Environment): DeployTarget => env.target ?? { kind: 'git' }

function dockerHost(t: DeployTarget): string {
  if (t.kind !== 'docker' || !t.host) return 'localhost'
  try { return new URL(t.host).hostname || 'localhost' } catch { return 'localhost' }
}

export function plan(doc: ProjectDoc, env: Environment): DeployPlan {
  const target = targetOf(env)
  const all = workloads(doc, env)
  const endpoints = all.filter((w) => w.public && w.port).flatMap((w) => {
    if (target.kind === 'docker') return [{ name: w.name, url: `http://${dockerHost(target)}:${hostPort(doc, env.id, w.name)}` }]
    if (target.kind === 'kubernetes') {
      const host = publicHost(doc, env, w.name, target)
      return host ? [{ name: w.name, url: `http://${host}${target.publicPort && target.publicPort !== 80 ? `:${target.publicPort}` : ''}` }] : []
    }
    return []
  })
  return {
    version: 1,
    project: slug(doc.name),
    env: env.id,
    target,
    namespace: target.kind === 'kubernetes' ? namespaceOf(doc, env) : undefined,
    builds: all.filter((w) => w.build).map((w) => ({ name: w.name, context: w.build! })),
    secrets: secrets(doc, env),
    endpoints,
    rollout: all.filter((w) => !w.schedule).map((w) => ({ kind: w.role === 'data' ? 'statefulset' : 'deployment', name: w.name })),
    checks: all.filter((w) => w.httpHealth && w.port && !w.schedule).map((w) => ({ name: w.name, port: w.port!, path: w.httpHealth! })),
    autoRollback: env.autoRollback,
  }
}

export function gatewayFiles(doc: ProjectDoc, n: SystemNode): Record<string, string> {
  const ups = doc.edges.filter((e) => e.source === n.id).map((e) => doc.nodes.find((x) => x.id === e.target)).filter((d): d is SystemNode => !!d && TECH_BY_ID[d.techId]?.category !== 'client')
  const upstream = (d: SystemNode) => `{$${connection(d).env}}`
  const routes = ups.length === 1
    ? `\treverse_proxy ${upstream(ups[0])}`
    : ups.map((d) => `\thandle_path /${d.name}/* {\n\t\treverse_proxy ${upstream(d)}\n\t}`).join('\n\n') + '\n\n\thandle {\n\t\trespond "no route" 404\n\t}'
  const dir = `gateways/${n.name}`
  return {
    [`${dir}/Caddyfile`]: `{\n\tadmin off\n\tauto_https off\n}\n\n:8080 {\n\thandle /healthz {\n\t\trespond "ok" 200\n\t}\n\n${ups.length ? routes : '\trespond "no upstreams connected yet" 503'}\n}\n`,
    [`${dir}/Dockerfile`]: 'FROM caddy:2.10-alpine\nCOPY Caddyfile /etc/caddy/Caddyfile\nEXPOSE 8080\n',
    [`${dir}/README.md`]: `# ${n.name}\n\nCaddy reverse proxy generated by Tessery.${ups.length > 1 ? ` Requests to \`/<service>/...\` go to that service: ${ups.map((d) => `\`/${d.name}/\``).join(', ')}.` : ''}\n`,
  }
}

export function deployFiles(doc: ProjectDoc): Record<string, string> {
  const f: Record<string, string> = {
    'compose.yaml': devCompose(doc),
    '.env.example': envExample(doc),
  }
  for (const n of doc.nodes) if (['api-gateway', 'graphql-gateway', 'load-balancer', 'reverse-proxy'].includes(n.techId)) Object.assign(f, gatewayFiles(doc, n))
  for (const env of doc.environments) {
    const p = plan(doc, env)
    f[`deploy/${env.id}/plan.json`] = JSON.stringify(p, null, 2) + '\n'
    if (p.target.kind === 'docker') f[`deploy/${env.id}/compose.yaml`] = envCompose(doc, env)
    if (p.target.kind === 'kubernetes') f[`deploy/${env.id}/k8s.yaml`] = manifests(doc, env)
  }
  return f
}
