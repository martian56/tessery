import type { Environment, ProjectDoc } from '../../domain/types'
import { envName, hostPort, localPorts, secrets, workloads, type Workload } from './runtime'
import { yamlDoc } from './yaml'

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'app'

function healthcheck(w: Workload) {
  if (w.health) return { test: ['CMD', ...w.health], interval: '5s', timeout: '5s', retries: 30, start_period: '10s' }
  return undefined
}

function dependsOn(doc: ProjectDoc, w: Workload, all: Workload[]) {
  const names = new Set(all.map((x) => x.name))
  const deps = doc.edges.filter((e) => e.source === w.node.id).map((e) => doc.nodes.find((n) => n.id === e.target)?.name).filter((n): n is string => !!n && names.has(n))
  if (!deps.length) return undefined
  return Object.fromEntries(deps.map((d) => {
    const target = all.find((x) => x.name === d)!
    return [d, { condition: target.role === 'data' && healthcheck(target) ? 'service_healthy' : 'service_started' }]
  }))
}

const mem = (m: string) => m.replace(/i$/, '').replace(/Mi$/, 'M').replace(/Gi$/, 'G').toLowerCase()

export function devCompose(doc: ProjectDoc): string {
  const all = workloads(doc).filter((w) => !w.schedule)
  const generated = new Set(secrets(doc).filter((s) => s.generate).map((s) => s.name))
  const withDefault = (v: string) => v.replace(/\$\{([A-Z0-9_]+)\}/g, (_, name: string) => `\${${name}:-${generated.has(name) ? 'dev' : ''}}`)
  const dev = (env: Record<string, string>) => Object.fromEntries(Object.entries(env).map(([k, v]) => [k, withDefault(v)]))
  const local = localPorts(doc)
  const services = Object.fromEntries(all.map((w) => [w.name, {
    build: w.build ? `./${w.build}` : undefined,
    image: w.image,
    command: w.command?.map((c) => c.replace(/\$\{([A-Z0-9_]+_PASSWORD)\}/g, '$${$1:-dev}')),
    environment: Object.keys(w.env).length ? dev(w.env) : undefined,
    ports: w.port ? [`\${${envName(w.name)}_PORT:-${local.get(w.name)}}:${w.port}`, ...w.ports.map((p) => `${local.get(`${w.name}:${p}`)}:${p}`)] : undefined,
    volumes: w.volume ? [`${w.name}-data:${w.volume}`] : undefined,
    healthcheck: healthcheck({ ...w, health: w.health?.map((c) => c.replace(/\$\{([A-Z0-9_]+_PASSWORD)\}/g, 'dev')) }),
    depends_on: dependsOn(doc, w, all),
  }]))
  const volumes = Object.fromEntries(all.filter((w) => w.volume).map((w) => [`${w.name}-data`, null]))
  const urls = all.filter((w) => w.port).map((w) => `#   ${w.name.padEnd(16)} localhost:${local.get(w.name)}`).join('\n')
  const head = `# Local development stack for ${doc.name}, generated by Tessery.\n# docker compose up --build\n# Passwords default to "dev"; copy .env.example to .env to change them.\n#\n# On this machine:\n${urls}\n`
  return head + yamlDoc({ name: slug(doc.name), services, volumes: Object.keys(volumes).length ? volumes : undefined } as never)
}

export function envCompose(doc: ProjectDoc, env: Environment): string {
  const all = workloads(doc, env)
  const scale = (w: Workload) => (w.role === 'app' ? Math.max(1, Math.round(w.node.replicas * env.scale)) : 1)
  const services: Record<string, unknown> = {}
  for (const w of all) {
    if (w.schedule) continue
    const replicas = scale(w)
    services[w.name] = {
      image: w.build ? `\${TESSERY_IMAGE_PREFIX}${w.name}:\${TESSERY_TAG}` : w.image,
      command: w.command,
      environment: Object.keys(w.env).length ? w.env : undefined,
      extra_hosts: w.role === 'app' && !(env.target?.kind === 'docker' && env.target.host) ? ['host.docker.internal:host-gateway'] : undefined,
      ports: w.public && w.port && replicas === 1 ? [`${hostPort(doc, env.id, w.name)}:${w.port}`] : undefined,
      volumes: w.volume ? [`${w.name}-data:${w.volume}`] : undefined,
      healthcheck: healthcheck(w),
      depends_on: dependsOn(doc, w, all.filter((x) => !x.schedule)),
      restart: 'unless-stopped',
      deploy: { replicas: replicas > 1 ? replicas : undefined, resources: { limits: { memory: mem(w.memory) } } },
      logging: { driver: 'json-file', options: { 'max-size': '10m', 'max-file': '3' } },
    }
  }
  const jobs = all.filter((w) => w.schedule)
  if (jobs.length) {
    services['scheduler'] = {
      image: 'mcuadros/ofelia:0.3.18',
      command: ['daemon', '--docker'],
      volumes: ['/var/run/docker.sock:/var/run/docker.sock:ro'],
      restart: 'unless-stopped',
      labels: Object.fromEntries(jobs.flatMap((w) => [
        [`ofelia.job-run.${w.name}.schedule`, `0 ${w.schedule}`],
        [`ofelia.job-run.${w.name}.image`, `\${TESSERY_IMAGE_PREFIX}${w.name}:\${TESSERY_TAG}`],
        [`ofelia.job-run.${w.name}.network`, `\${COMPOSE_PROJECT_NAME}_default`],
        [`ofelia.job-run.${w.name}.environment`, JSON.stringify(Object.entries(w.env).map(([k, v]) => `${k}=${v}`))],
      ])),
    }
  }
  const volumes = Object.fromEntries(all.filter((w) => w.volume).map((w) => [`${w.name}-data`, null]))
  return `# ${env.name} stack for ${doc.name}, generated by Tessery. Deployed by the Tessery runner.\n` + yamlDoc({ services, volumes: Object.keys(volumes).length ? volumes : undefined } as never)
}

export function envExample(doc: ProjectDoc): string {
  const s = secrets(doc)
  if (!s.length) return '# Nothing to configure.\n'
  return s.map((x) => `# ${x.description}\n${x.name}=${x.generate ? 'dev' : ''}`).join('\n') + '\n'
}

