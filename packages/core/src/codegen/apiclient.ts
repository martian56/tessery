import type { SystemNode, Operation, ProjectDoc } from '../domain/types'
import { builtInAuth, devConnection } from './deploy/runtime'
import { restPrefix } from './services/model'

const camel = (s: string) => s.replace(/-(\w)/g, (_, c: string) => c.toUpperCase())
const WRITE = ['POST', 'PUT', 'PATCH']

function graphqlArgs(input: string | undefined, typed: boolean): string {
  if (!input) return ''
  const args = input.split(',').map((a) => a.trim()).filter(Boolean).map((a) => {
    const [name, type] = a.split(':').map((x) => x.trim())
    return typed ? `$${name}: ${type}` : `${name}: $${name}`
  })
  return `(${args.join(', ')})`
}

function method(svc: string, style: string, basePath: string, o: Operation, prefix: string): string {
  if (style === 'graphql') {
    const q = `${o.kind} ${o.name}${graphqlArgs(o.input, true)} { ${o.name}${graphqlArgs(o.input, false)} { id } }`
    return `    ${o.name}: (vars?: Record<string, unknown>, opts?: Opts) => gql(${svc}, ${JSON.stringify(q)}, vars, opts?.token),`
  }
  if (style === 'grpc') return `    ${o.name}: (req: unknown, opts?: Opts) => call(${svc}, 'POST', '/${basePath}/${o.name}', req, opts?.token),`
  const [m, raw] = o.kind.split(' ')
  const path = raw && prefix && !raw.startsWith(`${prefix}/`) ? prefix + raw : raw
  if (!path) return `    // ${o.name}: ${style} ${o.kind} has no HTTP route`
  const params = [...path.matchAll(/\{(\w+)\}/g)].map((x) => x[1])
  const hasBody = WRITE.includes(m)
  const args = [...params.map((p) => `${p}: string`), ...(hasBody ? ['body: unknown'] : []), 'opts?: Opts'].join(', ')
  const url = '`' + path.replace(/\{(\w+)\}/g, '${encodeURIComponent($1)}') + '`'
  return `    ${o.name}: (${args}) => call(${svc}, '${m}', ${url}, ${hasBody ? 'body' : 'undefined'}, opts?.token),`
}

export function apiClient(doc: ProjectDoc): string {
  const specs = Object.values(doc.apis).map((sp) => ({ sp, node: doc.nodes.find((n) => n.id === sp.nodeId) })).filter((x): x is { sp: typeof x.sp; node: SystemNode } => !!x.node)
  const devUrls = specs.map(({ node }) => `  ${JSON.stringify(node.name)}: ${JSON.stringify(devConnection(node, doc).url)},`).join('\n')
  const groups = specs.map(({ sp, node }) => {
    const svc = JSON.stringify(node.name)
    return `  ${camel(node.name)}: {\n${sp.operations.map((o) => method(svc, sp.style, sp.basePath, o, restPrefix(sp))).join('\n')}\n  },`
  }).join('\n')
  return `// Typed client for every designed operation, generated by Tessery.
// On the server it calls each service at <SERVICE>_URL. In the browser it goes through /api/<service>.
const DEV_URLS: Record<string, string> = {
${devUrls}
}

export function serviceUrl(service: string): string {
  if (typeof window !== 'undefined') return \`/api/\${service}\`
  const key = service.toUpperCase().replace(/[^A-Z0-9]+/g, '_') + '_URL'
  return process.env[key] ?? DEV_URLS[service] ?? 'http://localhost:8080'
}

/** \`token\` calls on behalf of a signed-in user from server code; in the browser the session cookie does it. */
export interface Opts { token?: string }

async function call<T>(service: string, method: string, path: string, body?: unknown, token?: string): Promise<T> {
  const r = await fetch(serviceUrl(service) + path, {
    method,
    body: body === undefined ? undefined : JSON.stringify(body),
    headers: { ...(body === undefined ? {} : { 'content-type': 'application/json' }), ...(token ? { authorization: \`Bearer \${token}\` } : {}) },
    cache: 'no-store',
  })
  if (!r.ok) throw new Error(\`\${method} \${path} returned \${r.status}\`)
  return r.status === 204 ? (undefined as T) : r.json()
}

async function gql<T>(service: string, query: string, variables?: unknown, token?: string): Promise<T> {
  return (await call<{ data: T }>(service, 'POST', '/graphql', { query, variables }, token)).data
}

export const api = {
${groups}
}
`
}

export function apiProxy(doc: ProjectDoc, app: SystemNode): string {
  const auth = builtInAuth(doc)?.name
  const allowed = [...new Set([...doc.edges.filter((e) => e.source === app.id).map((e) => doc.nodes.find((n) => n.id === e.target)?.name), auth])].filter((n): n is string => !!n)
  return `import { serviceUrl } from '@/lib/api'

const ALLOWED = new Set(${JSON.stringify(allowed)})

async function forward(req: Request, ctx: { params: Promise<{ service: string; path?: string[] }> }) {
  const { service, path = [] } = await ctx.params
  if (!ALLOWED.has(service)) return Response.json({ error: 'unknown service' }, { status: 404 })
  const url = new URL(req.url)
  const target = serviceUrl(service) + '/' + path.map(encodeURIComponent).join('/') + url.search
  const headers = new Headers(req.headers)
  headers.delete('host')
  const body = req.method === 'GET' || req.method === 'HEAD' ? undefined : await req.arrayBuffer()
  try {
    const r = await fetch(target, { method: req.method, headers, body, redirect: 'manual', cache: 'no-store' })
    return new Response(r.body, { status: r.status, headers: r.headers })
  } catch {
    return Response.json({ error: \`\${service} is unreachable\` }, { status: 502 })
  }
}

export { forward as GET, forward as POST, forward as PUT, forward as PATCH, forward as DELETE }
export const dynamic = 'force-dynamic'
`
}
