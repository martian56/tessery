import type { ApiSpec, ApiStyle, SystemNode, Operation, ProjectDoc } from '../../domain/types'
import { LANGUAGE_BY_ID } from '../../catalog/languages'
import { TECH_BY_ID } from '../../catalog/technologies'
import { connectionUrl } from '../backend'

export type Files = Record<string, string>
export type Kind = 'api' | 'worker' | 'cron'
export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'

export interface Route {
  op: Operation
  name: string
  method: HttpMethod
  path: string
  params: string[]
}

export interface Dependency {
  name: string
  techId: string
  env: string
  url: string
}

export interface ServiceModel {
  doc: ProjectDoc
  node: SystemNode
  kind: Kind
  name: string
  dir: string
  language: string
  framework: string
  frameworkId: string
  style: ApiStyle
  port: number
  spec?: ApiSpec
  routes: Route[]
  operations: Operation[]
  deps: Dependency[]
  sources: string[]
  schedule?: string
  concurrency: number
}

const METHODS = new Set(['GET', 'POST', 'PUT', 'PATCH', 'DELETE'])

export const envName = (s: string) => s.toUpperCase().replace(/[^A-Z0-9]+/g, '_')
export const camel = (s: string) => s.replace(/[-_\s]+(\w)/g, (_, c: string) => c.toUpperCase()).replace(/^\w/, (c) => c.toLowerCase())
export const pascal = (s: string) => camel(s).replace(/^\w/, (c) => c.toUpperCase())
export const snake = (s: string) => camel(s).replace(/([A-Z])/g, '_$1').toLowerCase().replace(/^_/, '')
export const ident = (s: string) => s.replace(/[^A-Za-z0-9_]/g, '_')

export function httpRoute(op: Operation): Route | null {
  const [m, path] = op.kind.trim().split(/\s+/)
  const method = (m ?? '').toUpperCase()
  if (!METHODS.has(method) || !path?.startsWith('/')) return null
  return { op, name: camel(op.name || `${method.toLowerCase()} ${path}`), method: method as HttpMethod, path, params: [...path.matchAll(/\{(\w+)\}/g)].map((x) => x[1]) }
}

export function restPrefix(spec?: Pick<ApiSpec, 'style' | 'basePath'>): string {
  if (!spec || ['graphql', 'grpc', 'websocket', 'trpc', 'soap'].includes(spec.style)) return ''
  const p = (spec.basePath ?? '').trim().replace(/\/+$/, '')
  return p.startsWith('/') ? p : ''
}

export function buildModel(doc: ProjectDoc, n: SystemNode): ServiceModel {
  const spec = doc.apis[n.id]
  const kind: Kind = n.techId === 'worker' ? 'worker' : n.techId === 'cron' ? 'cron' : 'api'
  const language = String(spec?.language ?? n.config.language ?? 'TypeScript')
  const framework = String(spec?.framework ?? n.config.framework ?? '')
  const frameworkId = LANGUAGE_BY_ID[language]?.frameworks.find((f) => f.name === framework || f.id === framework)?.id ?? ''
  const ops = spec?.operations ?? []
  const prefix = restPrefix(spec)
  const routes = ops.map(httpRoute).filter((r): r is Route => !!r).map((r) => (prefix && !r.path.startsWith(`${prefix}/`) ? { ...r, path: prefix + r.path } : r))
  const deps = doc.edges
    .filter((e) => e.source === n.id)
    .map((e) => doc.nodes.find((x) => x.id === e.target))
    .filter((d): d is SystemNode => !!d && TECH_BY_ID[d.techId]?.category !== 'client')
    .map((d) => ({ name: d.name, techId: d.techId, env: `${envName(d.name)}_URL`, url: connectionUrl(d, doc) }))
  const sources = doc.edges.filter((e) => e.target === n.id).map((e) => doc.nodes.find((x) => x.id === e.source)?.name).filter((x): x is string => !!x)
  return {
    doc, node: n, kind, name: n.name, dir: `services/${n.name}`,
    language, framework, frameworkId,
    style: spec?.style ?? 'rest',
    port: Number(n.config.port ?? 8080),
    spec, routes, operations: ops.filter((o) => !httpRoute(o)), deps, sources,
    schedule: n.techId === 'cron' ? String(n.config.schedule ?? '0 * * * *') : undefined,
    concurrency: Number(n.config.concurrency ?? 1),
  }
}

export function stepLines(op: Operation): string[] {
  const lines = [op.summary || op.name, ...op.steps.map((s, i) => `${i + 1}. ${s}`)]
  if (op.auth !== 'public') lines.push(`Auth: ${op.auth}`)
  if (op.rateLimit) lines.push(`Rate limit: ${op.rateLimit}`)
  return lines.filter(Boolean)
}

export function comment(lines: string[], prefix: string, indent = ''): string {
  return lines.map((l) => `${indent}${prefix} ${l}`).join('\n')
}

export function readme(m: ServiceModel, run: string, notes: string[] = []): string {
  const what = m.kind === 'api' ? `${m.style.toUpperCase()} service` : m.kind === 'worker' ? 'background worker' : `scheduled job (\`${m.schedule}\`)`
  const deps = m.deps.length ? m.deps.map((d) => `| \`${d.env}\` | ${d.name} | \`${d.url}\` |`).join('\n') : '| none | | |'
  const ops = m.spec?.operations.length ? m.spec.operations.map((o) => `- \`${o.kind}\` ${o.name}: ${o.summary}`).join('\n') : '- none designed yet'
  return `# ${m.name}

${m.language} ${what}, generated by Tessery from the project design.${m.node.notes ? `\n\n${m.node.notes}` : ''}

## Run

    ${run}

or build the container: \`docker build -t ${m.name} .\`

The service listens on \`PORT\` (default ${m.port}) and answers \`GET /healthz\`.
Handlers that are not written yet return HTTP 501 with the steps from the design.

## Configuration

| Variable | Dependency | Example |
|---|---|---|
${deps}

Telemetry goes to \`OTEL_EXPORTER_OTLP_ENDPOINT\` when it is set.

## Operations

${ops}
${notes.length ? `\n## Notes\n\n${notes.map((x) => `- ${x}`).join('\n')}\n` : ''}`
}

export function envExample(m: ServiceModel): string {
  return [`PORT=${m.port}`, ...m.deps.map((d) => `${d.env}=${d.url}`), 'OTEL_SERVICE_NAME=' + m.name, '# OTEL_EXPORTER_OTLP_ENDPOINT=http://otel-collector:4318', ''].join('\n')
}

export function notImplementedBody(name: string): string {
  return JSON.stringify({ error: 'not_implemented', operation: name })
}
