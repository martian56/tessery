import RUST_DB from '../runtime/rust-db.txt'
import RUST_SESSION from '../runtime/rust-session.txt'
import { sqlType } from '../backend'
import { builtInAuth } from '../deploy/runtime'
import { type CrudRoute, type DataAccess, columnTypes, dataAccess, orderBy, primaryKey, writable } from './crud'
import { type Files, type Route, type ServiceModel, comment, envExample, ident, readme, snake, stepLines } from './model'
import { ownerColumn } from './typescript'

const fn = (name: string) => snake(name).replace(/[^a-z0-9_]/g, '_')
const rstr = (v: string) => JSON.stringify(v)
const rustConst = (name: string) => ident(name).toUpperCase()
const guarded = (m: ServiceModel, r: Route) => !!builtInAuth(m.doc) && (r.op.auth === 'user' || r.op.auth === 'admin')
const pathParams = (r: Route) => [...r.path.matchAll(/\{(\w+)\}/g)].map((x) => x[1])

/** How one web framework reads a request and sends a reply, for the generated handlers. */
interface Adapter {
  args: (r: Route, c: CrudRoute | undefined, guard: boolean) => string[]
  param: (p: string) => string
  query: string
  ret: string
}

const AXUM: Adapter = {
  args: (r, c, guard) => [
    ...(c && pathParams(r).length ? ['Path(path): Path<HashMap<String, String>>'] : []),
    ...(guard ? ['headers: HeaderMap'] : []),
    ...(c?.action === 'list' ? ['Query(query): Query<HashMap<String, String>>'] : []),
    ...(c && (c.action === 'create' || c.action === 'update') ? ['body: String'] : []),
  ],
  param: (p) => `path[${rstr(p)}].as_str()`,
  query: '&query',
  ret: 'Response',
}

const ACTIX: Adapter = {
  args: (_r, c, guard) => [
    ...(c || guard ? ['req: HttpRequest'] : []),
    ...(c?.action === 'list' ? ['query: web::Query<HashMap<String, String>>'] : []),
    ...(c && (c.action === 'create' || c.action === 'update') ? ['body: String'] : []),
  ],
  param: (p) => `req.match_info().get(${rstr(p)}).unwrap_or("")`,
  query: '&query.into_inner()',
  ret: 'HttpResponse',
}

/** One handler: sign-in checks, then the CRUD call or a 501. */
function rustHandler(m: ServiceModel, r: Route, c: CrudRoute | undefined, a: Adapter, db: boolean): string {
  // Sign-in is checked by the session module, which comes with the database layer.
  const guard = db && guarded(m, r)
  const lines: string[] = []
  if (guard) {
    lines.push(`let Some(session) = signed_in(${a === AXUM ? '&headers' : '&req'}) else { return reply(401, json!({ "error": "unauthorized" })) };`)
    if (r.op.auth === 'admin') lines.push('if session.role != "admin" { return reply(403, json!({ "error": "forbidden" })) }')
  }
  if (c) {
    const owner = guard ? ownerColumn(c) : undefined
    const pairs = [...(c.parent ? [`(${rstr(c.parent.column)}, ${a.param(c.parent.param)})`] : []), ...(owner ? [`(${rstr(owner)}, session.sub.as_str())`] : [])]
    const filter = `&[${pairs.join(', ')}]`
    const id = c.idParam ? a.param(c.idParam) : '""'
    const t = `tables::${rustConst(c.table.name)}`
    const call = {
      list: `${t}.list(${a.query}, ${filter})`,
      get: `${t}.get(${id}, ${filter})`,
      create: `${t}.create(&body, ${filter})`,
      update: `${t}.update(${id}, &body, ${filter})`,
      delete: `${t}.remove(${id}, ${filter})`,
    }[c.action]
    lines.push(`send(${call}.await)`)
  } else {
    lines.push(`not_implemented(${rstr(r.name)})`)
  }
  return `
${comment(stepLines(r.op), '///')}
async fn ${fn(r.name)}(${a.args(r, c, guard).join(', ')}) -> ${a.ret} {
${lines.map((l) => `    ${l}`).join('\n')}
}`
}

/** The database layer, session checks and table metadata, when the service has designed CRUD. */
function rustData(m: ServiceModel, da: DataAccess | undefined, f: Files) {
  if (!da) return
  f[`${m.dir}/src/db.rs`] = RUST_DB
  if (builtInAuth(m.doc)) f[`${m.dir}/src/session.rs`] = RUST_SESSION
  for (const mg of da.migrations) f[`${m.dir}/migrations/${da.node.name}/${mg.file}`] = mg.sql
  const used = [...new Map(da.routes.map((c) => [c.table.name, c.table])).values()]
  f[`${m.dir}/src/tables.rs`] = `//! The tables this service reads and writes, with the types values are cast to. Generated by Tessery.

use crate::db::Table;

/// Migrations in the order they apply, built into the binary.
pub const MIGRATIONS: &[(&str, &str)] = &[
${[...da.migrations].sort((x, y) => (x.file < y.file ? -1 : 1)).map((mg) => `    (${rstr(mg.file)}, include_str!(${rstr(`../migrations/${da.node.name}/${mg.file}`)})),`).join('\n')}
];
${used.map((t) => `
pub const ${rustConst(t.name)}: Table = Table {
    name: ${rstr(t.name)},
    key: ${rstr(primaryKey(t)!.name)},
    order: ${rstr(orderBy(t))},
    types: &[${Object.entries(columnTypes(t, (c) => sqlType(c, 'pg'))).map(([k, v]) => `(${rstr(k)}, ${rstr(v)})`).join(', ')}],
    writable: &[${writable(t).map(rstr).join(', ')}],
};`).join('\n')}
`
}

const crudOf = (da: DataAccess | undefined, r: Route) => da?.routes.find((c) => c.route === r)
/** Whether any route still answers 501, so the helper for that is needed. */
const stubs = (m: ServiceModel, da: DataAccess | undefined) => m.routes.some((r) => !crudOf(da, r))

function pick(m: ServiceModel): { s: 'axum' | 'actix'; note?: string } {
  if (m.frameworkId === 'actix') return { s: 'actix' }
  if (m.kind === 'api' && ['tonic', 'async-graphql'].includes(m.frameworkId)) {
    return { s: 'axum', note: `${m.framework} code is not generated yet. The ${m.style === 'grpc' ? 'proto' : 'schema'} is included; HTTP routes and health use Axum.` }
  }
  return { s: 'axum' }
}

function config(m: ServiceModel): string {
  return `use std::collections::HashMap;

/// Runtime configuration, read once from the environment.
pub struct Config {
    pub port: u16,
    pub dependencies: HashMap<&'static str, String>,
}

impl Config {
    pub fn from_env() -> Self {
        let var = |k: &str, d: &str| std::env::var(k).unwrap_or_else(|_| d.to_owned());
        Self {
            port: var("PORT", "${m.port}").parse().expect("PORT must be a number"),
            dependencies: HashMap::from([
${m.deps.map((d) => `                ("${d.env}", var("${d.env}", "${d.url}")),`).join('\n')}
            ]),
        }
    }
}
`
}

function axumMain(m: ServiceModel, da: DataAccess | undefined): string {
  const methods = [...new Set(['get', ...m.routes.map((r) => r.method.toLowerCase())])].sort().join(', ')
  const crud = m.routes.filter((r) => crudOf(da, r))
  const auth = m.routes.some((r) => guarded(m, r))
  const extract = [...(crud.some((r) => pathParams(r).length) ? ['Path'] : []), ...(crud.some((r) => crudOf(da, r)!.action === 'list') ? ['Query'] : [])]
  return `mod config;${da ? '\nmod db;\nmod tables;' : ''}${da && builtInAuth(m.doc) ? '\nmod session;' : ''}

${da ? 'use std::collections::HashMap;\n\n' : ''}use axum::{Json, Router, ${extract.length ? `extract::{${extract.join(', ')}}, ` : ''}http::{${auth && da ? 'HeaderMap, ' : ''}StatusCode${da ? ', header' : ''}}, response::{IntoResponse, Response}, routing::{${methods}}};
use serde_json::${da && auth ? '{Value, json}' : 'json'};

#[tokio::main]
async fn main() {
    tracing_subscriber::fmt().with_env_filter(tracing_subscriber::EnvFilter::try_from_default_env().unwrap_or_else(|_| "info".into())).init();
    let cfg = config::Config::from_env();
    tracing::info!(dependencies = cfg.dependencies.len(), "starting ${m.name}");
${da ? `    db::open(&cfg.dependencies[${rstr(da.dep.env)}], tables::MIGRATIONS).await;\n` : ''}
    let app = Router::new()
        .route("/healthz", get(|| async { Json(json!({ "status": "ok" })) }))
${m.routes.map((r) => `        .route("${r.path}",${r.method.toLowerCase()}(${fn(r.name)}))`).join('\n')};

    let listener = tokio::net::TcpListener::bind(("0.0.0.0", cfg.port)).await.expect("bind");
    tracing::info!(port = cfg.port, "listening");
    axum::serve(listener, app).with_graceful_shutdown(async { let _ = tokio::signal::ctrl_c().await; }).await.expect("server");
}

${stubs(m, da) ? `fn not_implemented(operation: &str) -> Response {
    (StatusCode::NOT_IMPLEMENTED, Json(json!({ "error": "not_implemented", "operation": operation }))).into_response()
}
` : ''}${da ? `
fn send(r: db::Reply) -> Response {
    let status = StatusCode::from_u16(r.status).unwrap_or(StatusCode::INTERNAL_SERVER_ERROR);
    match r.body {
        Some(body) => (status, [(header::CONTENT_TYPE, "application/json")], body).into_response(),
        None => status.into_response(),
    }
}
${auth ? `
fn reply(status: u16, body: Value) -> Response {
    send(db::error(status, body))
}

fn signed_in(headers: &HeaderMap) -> Option<session::Session> {
    let get = |k: &str| headers.get(k).and_then(|v| v.to_str().ok());
    session::from_headers(get("authorization"), get("cookie"))
}
` : ''}` : ''}${m.routes.map((r) => rustHandler(m, r, crudOf(da, r), AXUM, !!da)).join('\n')}
`
}

function actixMain(m: ServiceModel, da: DataAccess | undefined): string {
  const auth = m.routes.some((r) => guarded(m, r))
  return `mod config;${da ? '\nmod db;\nmod tables;' : ''}${da && builtInAuth(m.doc) ? '\nmod session;' : ''}

${da ? 'use std::collections::HashMap;\n\n' : ''}use actix_web::{App, ${da ? 'HttpRequest, ' : ''}HttpResponse, HttpServer, ${da ? 'http::StatusCode, ' : ''}web};
use serde_json::${da && auth ? '{Value, json}' : 'json'};

#[actix_web::main]
async fn main() -> std::io::Result<()> {
    tracing_subscriber::fmt().init();
    let cfg = config::Config::from_env();
    tracing::info!(port = cfg.port, dependencies = cfg.dependencies.len(), "starting ${m.name}");
${da ? `    db::open(&cfg.dependencies[${rstr(da.dep.env)}], tables::MIGRATIONS).await;\n` : ''}    HttpServer::new(|| {
        App::new()
            .route("/healthz", web::get().to(|| async { HttpResponse::Ok().json(json!({ "status": "ok" })) }))
${m.routes.map((r) => `            .route("${r.path}", web::${r.method.toLowerCase()}().to(${fn(r.name)}))`).join('\n')}
    })
    .bind(("0.0.0.0", cfg.port))?
    .run()
    .await
}

${stubs(m, da) ? `fn not_implemented(operation: &str) -> HttpResponse {
    HttpResponse::NotImplemented().json(json!({ "error": "not_implemented", "operation": operation }))
}
` : ''}${da ? `
fn send(r: db::Reply) -> HttpResponse {
    let mut res = HttpResponse::build(StatusCode::from_u16(r.status).unwrap_or(StatusCode::INTERNAL_SERVER_ERROR));
    match r.body {
        Some(body) => res.content_type("application/json").body(body),
        None => res.finish(),
    }
}
${auth ? `
fn reply(status: u16, body: Value) -> HttpResponse {
    send(db::error(status, body))
}

fn signed_in(req: &HttpRequest) -> Option<session::Session> {
    let get = |k: &str| req.headers().get(k).and_then(|v| v.to_str().ok());
    session::from_headers(get("authorization"), get("cookie"))
}
` : ''}` : ''}${m.routes.map((r) => rustHandler(m, r, crudOf(da, r), ACTIX, !!da)).join('\n')}
`
}

function workerMain(m: ServiceModel): string {
  if (m.kind === 'cron') return `mod config;

/// Runs once per schedule (${m.schedule}); the platform starts the container on that schedule.
fn main() {
    let cfg = config::Config::from_env();
    println!("${m.name} started with {} dependencies", cfg.dependencies.len());
}
`
  return `mod config;

use std::time::Duration;

/// Consumes work from: ${m.sources.join(', ') || 'nothing connected yet'}. Replace next_job with the client for that source.
async fn next_job() -> Option<String> {
    tokio::time::sleep(Duration::from_secs(1)).await;
    None
}

#[tokio::main]
async fn main() {
    tracing_subscriber::fmt().init();
    let cfg = config::Config::from_env();
    let workers: usize = std::env::var("CONCURRENCY").ok().and_then(|v| v.parse().ok()).unwrap_or(${m.concurrency});
    for _ in 0..workers.max(1) {
        tokio::spawn(async {
            loop {
                if let Some(job) = next_job().await {
                    tracing::info!(%job, "received job");
                }
            }
        });
    }
    let health = axum::Router::new().route("/healthz", axum::routing::get(|| async { r#"{"status":"ok"}"# }));
    let listener = tokio::net::TcpListener::bind(("0.0.0.0", cfg.port)).await.expect("bind");
    axum::serve(listener, health).await.expect("server");
}
`
}

export function rustService(m: ServiceModel): Files {
  const { s, note } = pick(m)
  const crate = ident(m.name).replace(/_/g, '-').toLowerCase()
  const f: Files = {}
  const da = m.kind === 'api' && m.style === 'rest' ? dataAccess(m) : undefined
  rustData(m, da, f)
  f[`${m.dir}/src/config.rs`] = config(m)
  f[`${m.dir}/src/main.rs`] = m.kind !== 'api' ? workerMain(m) : s === 'actix' ? actixMain(m, da) : axumMain(m, da)
  const web = s === 'actix' && m.kind === 'api' ? 'actix-web = "4"\n' : 'axum = "0.8"\n'
  const runtime = m.kind === 'cron' ? '' : `tokio = { version = "1", features = ["macros", "rt-multi-thread", "net", "signal", "time"] }\n${web}`
  f[`${m.dir}/Cargo.toml`] = `[package]
name = "${crate}"
version = "0.1.0"
edition = "2024"

[dependencies]
${runtime}serde_json = "1"${da ? `
tokio-postgres = "0.7"
deadpool-postgres = "0.14"` : ''}${da && builtInAuth(m.doc) ? `
hmac = "0.12"
sha2 = "0.10"
base64 = "0.22"` : ''}
tracing = "0.1"
tracing-subscriber = { version = "0.3", features = ["env-filter"] }

[profile.release]
strip = true
`
  f[`${m.dir}/Dockerfile`] = `FROM rust:1-slim-trixie AS build
WORKDIR /src
COPY . .
RUN cargo build --release && cp target/release/${crate} /app

FROM debian:trixie-slim
RUN useradd --system --uid 10001 app
COPY --from=build /app /usr/local/bin/app
USER app
EXPOSE ${m.port}
ENTRYPOINT ["/usr/local/bin/app"]
`
  f[`${m.dir}/.dockerignore`] = 'target\n'
  f[`${m.dir}/.env.example`] = envExample(m)
  f[`${m.dir}/README.md`] = readme(m, 'cargo run', note ? [note] : [])
  return f
}
